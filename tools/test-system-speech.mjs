import { SystemSpeech } from '../apps/ene-desktop/native/speech.mjs';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { performance } from 'node:perf_hooks';
const directory = new URL('../runtime/tts-tests/', import.meta.url).pathname.replace(/^\/(.:)/, '$1');
await mkdir(directory, { recursive: true });
const speech = new SystemSpeech({ helper: new URL('../apps/ene-desktop/native/speech-host.exe', import.meta.url).pathname.replace(/^\/(.:)/, '$1'), directory });
const voices = await speech.voices();
assert.ok(voices.length);
const voice = voices.find(v => v.language.startsWith('zh'))?.id || voices[0].id;
const text = '哼，才不是特意在等你。只是刚好有空而已。记得休息，笨蛋。';
const began = performance.now();
const result = await speech.render({ voice, text });
assert.ok(result.bytes > 44);
await writeFile(`${directory}/system-huihui.wav`, Buffer.from(result.audio.split(',')[1], 'base64'));
const report = { status: 'passed', backend: 'Windows System.Speech', voices, selected: voice, bytes: result.bytes, synthesisMs: Math.round(performance.now() - began), tests: ['installed_voice_listing','chinese_wav_generation'] };
const pending = speech.render({ voice, text: text.repeat(30) });
await new Promise(resolve => setTimeout(resolve, 100));
speech.stop();
assert.equal(await pending.catch(() => null), null);
report.tests.push('cancellation_discards_late_audio');
await assert.rejects(() => speech.render({ voice: 'not-installed', text }));
report.tests.push('unknown_voice_rejected');
await writeFile(`${directory}/system-report.json`, JSON.stringify(report, null, 2));
console.log(JSON.stringify(report));
